#!/usr/bin/env node
// Builds frontend/css/tailwind.css — the prebuilt Tailwind stylesheet the app
// ships instead of compiling Tailwind in the browser (audit OBS-11, triage 73).
//
// The output is committed, like js/i18n-catalog.js, so neither the Railway
// deploy nor the Android bundle needs Node or Tailwind installed. Re-run after
// adding Tailwind classes to index.html or any frontend/js file:
//   node scripts/build-tailwind-css.js          rebuild
//   node scripts/build-tailwind-css.js --check  fail if the committed file is stale
// Tailwind is pinned to the version the app previously loaded at runtime.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const TAILWIND = 'tailwindcss@3.4.17';
const root = path.resolve(__dirname, '..');
const config = path.join(__dirname, 'tailwind', 'tailwind.config.js');
const input = path.join(__dirname, 'tailwind', 'input.css');
const OUT = path.join(root, 'frontend', 'css', 'tailwind.css');
const HEADER = '/* Generated by scripts/build-tailwind-css.js (' + TAILWIND + ') - do not edit. */\n';

function build() {
    const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'cauldra-tw-')), 'tailwind.css');
    execFileSync('npx', ['--yes', TAILWIND, '-c', config, '-i', input, '-o', tmp, '--minify'],
        { cwd: root, stdio: ['ignore', 'ignore', 'inherit'], env: { ...process.env, BROWSERSLIST_IGNORE_OLD_DATA: '1' } });
    return HEADER + fs.readFileSync(tmp, 'utf8').trim() + '\n';
}

const css = build();
if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== css) {
        console.error('frontend/css/tailwind.css is stale: run node scripts/build-tailwind-css.js');
        process.exit(1);
    }
    console.log('frontend/css/tailwind.css is up to date');
} else {
    fs.writeFileSync(OUT, css);
    console.log('Wrote frontend/css/tailwind.css (' + css.length + ' bytes)');
}
